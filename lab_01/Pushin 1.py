k = float(input("Введите значение k: ")) #создаем переменные типа float для записи дробных чисел  
s = float(input("Введите значение s: "))
T1 = float(input("Введите значение T1: "))
T2 = float(input("Введите значение T2: "))
d = float(input("Введите значение d: "))
Q = k*s*(T1-T2)/d #записываем формулу
print(f"Тепловые потери стены Q = {Q:.4f}") #выводим Q и сокращаем до 4 знаков после запятой с помощью f строки

